import {chromium}from'playwright';
import {gameBuildBinding} from './game-build-binding.mjs';
import {mkdir,writeFile}from'node:fs/promises';
import assert from'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/tmp/mario-playwright/chromium-1148/chrome-linux/chrome',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-webgl']});
const page=await browser.newPage({viewport:{width:1024,height:900}});const errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
await page.goto(process.env.GAME_URL||'http://localhost:5173/');
await page.waitForFunction(()=>window.mario?.ready,{timeout:30000});
const buildBinding=await gameBuildBinding(page);
await mkdir('evidence/local/browser',{recursive:true});
await page.screenshot({path:'evidence/local/browser/title.png'});
let image=await page.evaluate(()=>window.mario.reset().image);
await writeFile('evidence/local/browser/initial.png',Buffer.from(image.split(',')[1],'base64'));
await page.evaluate(()=>window.mario.step(['right','b'],30));
let result=await page.evaluate(()=>window.marioDebug.snapshot());
assert.ok(result.player.x>40);assert.equal(result.frame,30);
await page.evaluate(()=>window.mario.step(['a'],30));
result=await page.evaluate(()=>window.marioDebug.snapshot());assert.ok(result.player.y<208);
await page.screenshot({path:'evidence/local/browser/jump.png'});
await page.getByRole('button',{name:'Pause · P',exact:true}).click();
assert.equal(await page.evaluate(()=>window.marioDebug.simulation.paused),true);
const paused=await page.evaluate(()=>window.mario.step(['right'],30));
assert.equal(paused.framesRequested,30);assert.equal(paused.framesAdvanced,0);
await page.getByRole('button',{name:'Resume · P',exact:true}).click();
await page.getByRole('button',{name:'Sound on · M',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Muted · M',exact:true}).count(),1);
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'evidence/local/browser/mobile.png'});
assert.ok(await page.locator('canvas').evaluate(c=>c.getBoundingClientRect().right)<=390);
assert.deepEqual(errors,[]);
await writeFile('evidence/browser-smoke.json',JSON.stringify({date:new Date().toISOString(),buildBinding,errors,result,checks:['startup','all_assets','title','reset','controller_native_frames','jump','pause_resume','mute','mobile_integer_scale'],screenshots:'evidence/local/browser'},null,2));
await browser.close();console.log('Browser startup, assets, native-frame controls, jump, pause/mute and mobile layout passed');
await import('./start-button-browser-test.mjs');
await import('./two-player-title-browser-test.mjs');
await import('./two-player-checkpoint-browser-test.mjs');
